-- PostgreSQL schema for the Rahti deployment (see postgres.yaml).
-- Mirrors the JPA entities in src/main/java/.../Model so Hibernate's ddl-auto=update finds
-- everything in place. Safe to run more than once.
--
-- Run against the Rahti database:
--   oc exec -i deploy/postgres -- psql -U appuser -d appdb < schema.sql

-- users (User.java). "user" is a reserved word in PostgreSQL, hence the plural.
CREATE TABLE IF NOT EXISTS users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(50)    NOT NULL UNIQUE,
    first_name       VARCHAR(100)   NOT NULL,
    last_name        VARCHAR(100)   NOT NULL,
    email            VARCHAR(100)   NOT NULL UNIQUE,
    password_hash    VARCHAR(255)   NOT NULL,
    created_at       TIMESTAMP(6)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Dashboard widget layout as JSON, owned by the frontend
    dashboard_layout VARCHAR(10000)
);

-- category (Category.java). user_id NULL = global default category shared by all users.
CREATE TABLE IF NOT EXISTS category (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL,
    user_id BIGINT REFERENCES users (id)
);

-- transaction (Transaction.java)
CREATE TABLE IF NOT EXISTS transaction (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount           NUMERIC(12, 2) NOT NULL,
    transaction_date DATE           NOT NULL,
    merchant         VARCHAR(150)   NOT NULL,
    description      VARCHAR(500),
    -- TransactionType enum stored as text. No CHECK constraint on purpose, see EnumCheckConstraintCleanup.
    transaction_type VARCHAR(255)   NOT NULL,
    category_id      BIGINT REFERENCES category (id),
    user_id          BIGINT         NOT NULL REFERENCES users (id)
);

-- budget (Budget.java). One spending limit per user, category and month ("YYYY-MM").
CREATE TABLE IF NOT EXISTS budget (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount       NUMERIC(12, 2) NOT NULL,
    budget_month VARCHAR(7)     NOT NULL,
    category_id  BIGINT         NOT NULL REFERENCES category (id),
    user_id      BIGINT         NOT NULL REFERENCES users (id),
    UNIQUE (user_id, category_id, budget_month)
);

CREATE INDEX IF NOT EXISTS idx_category_user_id ON category (user_id);
CREATE INDEX IF NOT EXISTS idx_transaction_user_id ON transaction (user_id);
CREATE INDEX IF NOT EXISTS idx_transaction_category_id ON transaction (category_id);
CREATE INDEX IF NOT EXISTS idx_budget_category_id ON budget (category_id);

-- Global default categories. CSV import and MerchantCategoryRules look these up by name
-- (findByNameAndUserIsNull), with "Other" as the fallback.
INSERT INTO category (name, user_id)
SELECT v.name, NULL
FROM (VALUES
    ('Food'),
    ('Transportation'),
    ('Entertainment'),
    ('Housing'),
    ('Utilities'),
    ('Healthcare'),
    ('Education'),
    ('Personal Care'),
    ('Salary'),
    ('Travel'),
    ('Shopping'),
    ('Other')
) AS v (name)
WHERE NOT EXISTS (
    SELECT 1 FROM category c WHERE c.name = v.name AND c.user_id IS NULL
);
